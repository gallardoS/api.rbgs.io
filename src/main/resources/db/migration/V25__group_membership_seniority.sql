-- Previous memberships did not record join time. Give legacy members a stable baseline;
-- subsequent joins receive a strictly increasing position while the group lock is held.
ALTER TABLE rbgs.group_members ADD COLUMN joined_order BIGINT GENERATED BY DEFAULT AS IDENTITY;
WITH legacy AS (
    SELECT account_id, row_number() OVER (ORDER BY group_id, account_id) AS position
    FROM rbgs.group_members
)
UPDATE rbgs.group_members m SET joined_order = legacy.position
FROM legacy WHERE m.account_id = legacy.account_id;
SELECT setval(pg_get_serial_sequence('rbgs.group_members', 'joined_order'),
    COALESCE((SELECT max(joined_order) FROM rbgs.group_members), 0) + 1, false);
CREATE UNIQUE INDEX group_members_joined_order ON rbgs.group_members(joined_order);
